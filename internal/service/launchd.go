package service

import (
	"os"
	"path/filepath"
	"runtime"
	"strconv"
	"strings"
)

// launchd (macOS) — a per-user LaunchAgent.
//
// RunAtLoad plus KeepAlive is launchd's equivalent of Restart=always at boot.
// A LaunchAgent runs as the logged-in user, which is the scope rcmanager wants.

const launchdLabel = "io.github.dumanhaydar.rcmanager"

func xmlEscape(s string) string {
	s = strings.ReplaceAll(s, "&", "&amp;")
	s = strings.ReplaceAll(s, "<", "&lt;")
	return strings.ReplaceAll(s, ">", "&gt;")
}

func plist(ctx Context) string {
	env := strings.Join(ctx.EnvLines(func(k, v string) string {
		return "\t\t<key>" + xmlEscape(k) + "</key> <string>" + xmlEscape(v) + "</string>"
	}), "\n")
	if env != "" {
		env += "\n"
	}

	return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- ` + xmlEscape(ctx.Description) + `
     Generated by ` + "`rcmanager service install`" + `. Re-run that to refresh it. -->
<plist version="1.0">
<dict>
	<key>Label</key>              <string>` + launchdLabel + `</string>
	<key>ProgramArguments</key>
	<array>
		<string>` + xmlEscape(ctx.Entrypoint) + `</string>
		<string>daemon</string>
		<string>--foreground</string>
	</array>
	<key>EnvironmentVariables</key>
	<dict>
		<key>RCMANAGER_HOME</key> <string>` + xmlEscape(ctx.RcmanHome) + `</string>
		<key>HOME</key>       <string>` + xmlEscape(ctx.Home) + `</string>
		<key>PATH</key>       <string>` + xmlEscape(ctx.Path) + `</string>
` + env + `	</dict>
	<key>WorkingDirectory</key>   <string>` + xmlEscape(ctx.Home) + `</string>
	<key>RunAtLoad</key>          <true/>
	<key>KeepAlive</key>          <true/>
	<key>ThrottleInterval</key>   <integer>5</integer>
	<key>ExitTimeOut</key>        <integer>90</integer>
	<key>StandardOutPath</key>    <string>` + xmlEscape(ctx.RcmanHome) + `/service.log</string>
	<key>StandardErrorPath</key>  <string>` + xmlEscape(ctx.RcmanHome) + `/service.log</string>
</dict>
</plist>
`
}

type launchd struct{}

func init() { register(launchd{}) }

func (launchd) ID() string          { return "launchd" }
func (launchd) DisplayName() string { return "launchd (LaunchAgent)" }
func (launchd) Priority() int       { return 90 }

func (launchd) Detect() Availability {
	if runtime.GOOS != "darwin" {
		return Availability{false, "launchd is macOS-only"}
	}
	if Which("launchctl") == "" {
		return Availability{false, "launchctl not found"}
	}
	return Availability{true, "launchd is available"}
}

func (launchd) UnitPath() string {
	home, _ := os.UserHomeDir()
	return filepath.Join(home, "Library", "LaunchAgents", launchdLabel+".plist")
}

func (launchd) Render(ctx Context) string { return plist(ctx) }

func domain() string { return "gui/" + strconv.Itoa(os.Getuid()) }

func (m launchd) Install(ctx Context) (Installed, error) {
	file := m.UnitPath()
	if err := os.MkdirAll(filepath.Dir(file), 0o755); err != nil {
		return Installed{}, err
	}
	if err := os.WriteFile(file, []byte(plist(ctx)), 0o644); err != nil {
		return Installed{}, err
	}

	var notes []string
	// bootout first, so a re-install picks up the new plist.
	Exec("launchctl", []string{"bootout", domain() + "/" + launchdLabel}, "")
	boot := Exec("launchctl", []string{"bootstrap", domain(), file}, "")
	if !boot.OK {
		legacy := Exec("launchctl", []string{"load", "-w", file}, "")
		if !legacy.OK {
			notes = append(notes, "could not load the agent: "+firstNonEmpty(boot.Err, legacy.Err))
		}
	}
	Exec("launchctl", []string{"enable", domain() + "/" + launchdLabel}, "")
	return Installed{Path: file, Notes: notes}, nil
}

func (m launchd) Uninstall() Removed {
	file := m.UnitPath()
	Exec("launchctl", []string{"bootout", domain() + "/" + launchdLabel}, "")
	Exec("launchctl", []string{"unload", "-w", file}, "")
	_, err := os.Stat(file)
	existed := err == nil
	if existed {
		_ = os.Remove(file)
	}
	return Removed{Removed: existed}
}

func (m launchd) Status() Status {
	list := Exec("launchctl", []string{"list"}, "")
	line := ""
	for _, l := range strings.Split(list.Out, "\n") {
		if strings.Contains(l, launchdLabel) {
			line = strings.TrimSpace(l)
			break
		}
	}
	_, err := os.Stat(m.UnitPath())
	installed := err == nil
	return Status{
		Installed: installed,
		Running:   line != "" && !strings.HasPrefix(line, "-"),
		Enabled:   installed,
		Detail:    orElse(line, "not loaded"),
	}
}

func (launchd) Start() Run {
	return Exec("launchctl", []string{"kickstart", domain() + "/" + launchdLabel}, "")
}

func (launchd) Stop() Run {
	return Exec("launchctl", []string{"bootout", domain() + "/" + launchdLabel}, "")
}

func (launchd) LogsHint() string { return `tail -f "$RCMANAGER_HOME/service.log"` }
