// systemd comes in two flavours.
//
// The USER manager is strongly preferred: rcmanager runs agent CLIs as the
// logged-in user, with that user's credentials and config. A system unit would
// need User=/Group= and root to install, and is only the right answer when
// there is no per-user manager (a bare container, or running as root).
//
// Lingering is what makes a user service start at boot and survive logout —
// without it the user manager stops with the last session.

func unitText(ctx Context, system bool) string {
	userLines := ""
	if system {
		userLines = "User=" + ctx.User + "\nGroup=" + ctx.User + "\n"
	}
	wantedBy := "default.target"
	if system {
		wantedBy = "multi-user.target"
	}
	env := strings.Join(ctx.EnvLines(func(k, v string) string { return "Environment=" + k + "=" + v }), "\n")
	if env != "" {
		env += "\n"
	}

	return `# ` + ctx.Description + `
#
# Generated by ` + "`rcmanager service install`" + `. Re-run that to refresh it.
# systemd manages rcmanager; rcmanager manages individual agent sessions.

[Unit]
Description=` + ctx.Description + `
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
ExecStart=` + ctx.Entrypoint + ` daemon --foreground
` + userLines + `Environment=RCMANAGER_HOME=` + ctx.RcmanHome + `
Environment=HOME=` + ctx.Home + `
Environment=PATH=` + ctx.Path + `
` + env + `WorkingDirectory=` + ctx.Home + `

Restart=always
RestartSec=5
TimeoutStopSec=30

# Only ever signal the daemon itself.
#
# systemd stops a *cgroup*, not a process, and every session rcmanager spawns
# starts life inside this unit's cgroup — so the default
# (KillMode=control-group, and mixed too at the end of its timeout) SIGKILLs
# every managed agent whenever the service is stopped or restarted.
# KillMode=process leaves them alone, which is the whole point: rcmanager detaches
# on SIGTERM and the next daemon adopts them. (This is the same reason sshd
# uses it to keep sessions alive across a restart.)
#
# rcmanager additionally launches each session in its own transient scope where
# systemd-run is available, so this is a second line of defence rather than
# the only one.
KillMode=process
KillSignal=SIGTERM

[Install]
WantedBy=` + wantedBy + `
`
}

var connectFailure = regexp.MustCompile(`(?i)Failed to connect|No medium|not been booted`)

// userManagerReachable reports whether a systemd user manager actually answers
// for this user. "degraded", "starting" and "running" all mean a manager
// answered; only a hard failure to connect means there is none.
func userManagerReachable() bool {
	if Which("systemctl") == "" {
		return false
	}
	r := Exec("systemctl", []string{"--user", "is-system-running"}, "")
	return !connectFailure.MatchString(r.Out + r.Err)
}

func systemdRunning() bool {
	_, err := os.Stat("/run/systemd/system")
	return err == nil
}

type systemdUser struct{}

func init() { register(systemdUser{}) }

func (systemdUser) ID() string          { return "systemd-user" }
func (systemdUser) DisplayName() string { return "systemd (user service)" }
func (systemdUser) Priority() int       { return 100 }

func (systemdUser) Detect() Availability {
	switch {
	case runtime.GOOS != "linux":
		return Availability{false, "systemd is Linux-only"}
	case Which("systemctl") == "":
		return Availability{false, "systemctl not found"}
	case !systemdRunning():
		return Availability{false, "systemd is not the running init"}
	case os.Geteuid() == 0:
		return Availability{false, "running as root — a system unit fits better"}
	case !userManagerReachable():
		return Availability{false, "no systemd user manager for this account"}
	}
	return Availability{true, "systemd user manager is available"}
}

func (systemdUser) UnitPath() string {
	home, _ := os.UserHomeDir()
	return filepath.Join(home, ".config", "systemd", "user", "rcmanager.service")
}

func (systemdUser) Render(ctx Context) string { return unitText(ctx, false) }

func (m systemdUser) Install(ctx Context) (Installed, error) {
	file := m.UnitPath()
	var notes []string

	if err := os.MkdirAll(filepath.Dir(file), 0o755); err != nil {
		return Installed{}, err
	}
	if err := os.WriteFile(file, []byte(unitText(ctx, false)), 0o644); err != nil {
		return Installed{}, err
	}

	Exec("systemctl", []string{"--user", "daemon-reload"}, "")
	if enabled := Exec("systemctl", []string{"--user", "enable", "rcmanager"}, ""); !enabled.OK {
		notes = append(notes, "could not enable the unit: "+enabled.Err)
	}

	// Without lingering the user manager exits with the last login, so nothing
	// survives a reboot.
	linger := Exec("loginctl", []string{"show-user", ctx.User, "--property=Linger"}, "")
	if !strings.Contains(linger.Out, "Linger=yes") {
		direct := Exec("loginctl", []string{"enable-linger", ctx.User}, "")
		sudo := Run{}
		if !direct.OK {
			sudo = Exec("sudo", []string{"-n", "loginctl", "enable-linger", ctx.User}, "")
		}
		if direct.OK || sudo.OK {
			notes = append(notes, "enabled user lingering, so rcmanager starts at boot without a login")
		} else {
			notes = append(notes, "lingering is off — rcmanager will NOT start at boot until you run: sudo loginctl enable-linger "+ctx.User)
		}
	}
	return Installed{Path: file, Notes: notes}, nil
}

func (m systemdUser) Uninstall() Removed {
	file := m.UnitPath()
	var notes []string
	Exec("systemctl", []string{"--user", "stop", "rcmanager"}, "")
	if disabled := Exec("systemctl", []string{"--user", "disable", "rcmanager"}, ""); !disabled.OK && disabled.Err != "" {
		notes = append(notes, disabled.Err)
	}
	_, err := os.Stat(file)
	existed := err == nil
	if existed {
		_ = os.Remove(file)
	}
	Exec("systemctl", []string{"--user", "daemon-reload"}, "")
	notes = append(notes, "user lingering was left enabled; disable it with `loginctl disable-linger` if nothing else needs it")
	return Removed{Removed: existed, Notes: notes}
}

func (m systemdUser) Status() Status {
	active := Exec("systemctl", []string{"--user", "is-active", "rcmanager"}, "").Out
	enabled := Exec("systemctl", []string{"--user", "is-enabled", "rcmanager"}, "").Out
	linger := Exec("loginctl", []string{"show-user", NewContext().User, "--property=Linger"}, "").Out
	_, err := os.Stat(m.UnitPath())
	return Status{
		Installed: err == nil,
		Running:   active == "active",
		Enabled:   enabled == "enabled",
		Detail:    "active=" + orUnknown(active) + " enabled=" + orUnknown(enabled) + " " + orElse(linger, "Linger=unknown"),
	}
}

func (systemdUser) Start() Run {
	return Exec("systemctl", []string{"--user", "start", "rcmanager"}, "")
}
func (systemdUser) Stop() Run        { return Exec("systemctl", []string{"--user", "stop", "rcmanager"}, "") }
func (systemdUser) LogsHint() string { return "journalctl --user -u rcmanager -f" }

type systemdSystem struct{}

func init() { register(systemdSystem{}) }

func (systemdSystem) ID() string          { return "systemd-system" }
func (systemdSystem) DisplayName() string { return "systemd (system service)" }
func (systemdSystem) Priority() int       { return 60 }

func (systemdSystem) Detect() Availability {
	switch {
	case runtime.GOOS != "linux":
		return Availability{false, "systemd is Linux-only"}
	case Which("systemctl") == "":
		return Availability{false, "systemctl not found"}
	case !systemdRunning():
		return Availability{false, "systemd is not the running init"}
	}
	if os.Geteuid() == 0 {
		return Availability{true, "running as root"}
	}
	if Exec("sudo", []string{"-n", "true"}, "").OK {
		return Availability{true, "passwordless sudo is available"}
	}
	return Availability{false, "needs root or passwordless sudo"}
}

func (systemdSystem) UnitPath() string          { return "/etc/systemd/system/rcmanager.service" }
func (systemdSystem) Render(ctx Context) string { return unitText(ctx, true) }

func (m systemdSystem) Install(ctx Context) (Installed, error) {
	file := m.UnitPath()
	// `tee` keeps the privileged write to one auditable command.
	if write := AsRoot([]string{"tee", file}, unitText(ctx, true)); !write.OK {
		return Installed{}, rcerr.New("could not write "+file+": "+write.Err, "")
	}
	var notes []string
	AsRoot([]string{"systemctl", "daemon-reload"}, "")
	if enabled := AsRoot([]string{"systemctl", "enable", "rcmanager"}, ""); !enabled.OK {
		notes = append(notes, "could not enable the unit: "+enabled.Err)
	}
	notes = append(notes, "the unit runs as "+ctx.User+"; that account must be logged in to the provider CLIs")
	return Installed{Path: file, Notes: notes}, nil
}

func (m systemdSystem) Uninstall() Removed {
	AsRoot([]string{"systemctl", "stop", "rcmanager"}, "")
	AsRoot([]string{"systemctl", "disable", "rcmanager"}, "")
	_, err := os.Stat(m.UnitPath())
	existed := err == nil
	AsRoot([]string{"rm", "-f", m.UnitPath()}, "")
	AsRoot([]string{"systemctl", "daemon-reload"}, "")
	return Removed{Removed: existed}
}

func (m systemdSystem) Status() Status {
	active := Exec("systemctl", []string{"is-active", "rcmanager"}, "").Out
	_, err := os.Stat(m.UnitPath())
	return Status{
		Installed: err == nil,
		Running:   active == "active",
		Enabled:   Exec("systemctl", []string{"is-enabled", "rcmanager"}, "").Out == "enabled",
		Detail:    "active=" + orUnknown(active),
	}
}

func (systemdSystem) Start() Run       { return AsRoot([]string{"systemctl", "start", "rcmanager"}, "") }
func (systemdSystem) Stop() Run        { return AsRoot([]string{"systemctl", "stop", "rcmanager"}, "") }
func (systemdSystem) LogsHint() string { return "journalctl -u rcmanager -f" }

func orUnknown(s string) string { return orElse(s, "unknown") }

func orElse(s, fallback string) string {
	if strings.TrimSpace(s) == "" {
		return fallback
	}
	return s
}
